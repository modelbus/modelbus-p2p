// Same logic as i18n-update.mjs: drop existing nav / home / wallet / models
// derived lines, then append fresh ones. The home / wallet / models blocks
// did not exist in the previous iteration so this is mostly additive.
async function run() {
  for (const [lang, pack] of Object.entries(PACKS)) {
    const file = path.join(i18nDir, `${lang}.ts`);
    const text = await fs.readFile(file, 'utf-8');

    const q = (s) => String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");

    // Drop existing derived lines so the patch is idempotent.
    let out = text;
    const dropKeys = ['models', 'wallet'];
    for (const k of dropKeys) {
      out = out.replace(new RegExp(`\\n    ${k}:\\s*'[^']*',?`), '');
    }
    // Drop any existing home / wallet / models blocks entirely.
    out = out.replace(/\n  home:\s*\{[\s\S]*?\n  \},\n/g, '\n');
    out = out.replace(/\n  wallet:\s*\{[\s\S]*?\n  \},\n/g, '\n');
    out = out.replace(/\n  models:\s*\{[\s\S]*?\n  \},\n/g, '\n');

    // Rebuild nav block with all five keys. Preserve the existing logs /
    // settings translations from the file (since navLabels were already
    // present in the previous iteration).
    const existingLogs = out.match(/  nav:\s*\{[\s\S]*?logs:\s*'([^']*)'/) || ['', 'Logs'];
    const existingSettings = out.match(/  nav:\s*\{[\s\S]*?settings:\s*'([^']*)'/) || ['', 'Settings'];
    const navBlock =
      `\n  nav: {\n` +
      `    home: '${q(pack.nav.home ?? (lang.startsWith('zh') ? '首页' : 'Home'))}',\n` +
      `    models: '${q(pack.nav.models)}',\n` +
      `    wallet: '${q(pack.nav.wallet)}',\n` +
      `    logs: '${q(existingLogs[1])}',\n` +
      `    settings: '${q(existingSettings[1])}',\n` +
      `  },`;
    out = out.replace(/  nav:\s*\{[\s\S]*?\},/, navBlock);

    // Make sure setup.models exists for type-compatibility with zh-CN.
    out = out.replace(/(\n  setup:\s*\{[\s\S]*?)(  \},\n)/, (m, head, tail) => {
      if (!/\n    models:/.test(head)) {
        const label = (pack.home?.models) ?? 'Models';
        const safe = label.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
        return head + `    models: '${safe}',\n` + tail;
      }
      return m;
    });

    // Append home / wallet / models blocks before the final closing `};`.
    // Multi-line values use a backtick template so the embedded newlines
    // survive into the source file.
    const homeLines = Object.entries(pack.home)
      .map(([k, v]) => {
        if (v.includes('\n')) return `    ${k}: \`${v}\`,`;
        return `    ${k}: '${q(v)}',`;
      })
      .join('\n');

    const walletAxis = Object.entries(pack.wallet.axis)
      .map(([k, v]) => `      ${k}: '${q(v)}',`)
      .join('\n');
    const walletLines =
      Object.entries(pack.wallet)
        .filter(([, v]) => typeof v === 'string')
        .map(([k, v]) => {
          if (v.includes('\n')) return `    ${k}: \`${v}\`,`;
          return `    ${k}: '${q(v)}',`;
        })
        .join('\n') +
      `\n    axis: {\n${walletAxis}\n    },`;

    const modelsLines = Object.entries(pack.models)
      .map(([k, v]) => {
        if (v.includes('\n')) return `    ${k}: \`${v}\`,`;
        return `    ${k}: '${q(v)}',`;
      })
      .join('\n');

    const blocks =
      `\n  home: {\n${homeLines}\n  },\n` +
      `  wallet: {\n${walletLines}\n  },\n` +
      `  models: {\n${modelsLines}\n  },\n`;

    out = out.replace(/(\n\};)\s*$/, `${blocks}$1`);

    await fs.writeFile(file, out);
    console.log(`updated ${lang}`);
  }
}

run().catch((err) => { console.error(err); process.exit(1); });
